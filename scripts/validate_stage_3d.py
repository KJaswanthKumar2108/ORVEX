"""Stage 3D End-to-End Validation Script

Validates that telemetry generated by the simulator scenarios sent to the FastAPI
telemetry API endpoint automatically triggers the analytics pipeline, stores telemetry,
and persists finalized energy wastage events in TimescaleDB, with complete idempotency
and cleanup.
"""

from datetime import datetime, timedelta, timezone
from decimal import Decimal
import os
import sys
import time
from typing import Any
from uuid import UUID, uuid4

from fastapi.testclient import TestClient
from sqlalchemy import func, select
from sqlalchemy.orm import Session

# Add project root and backend to sys.path
sys.path.insert(0, os.path.abspath("."))
sys.path.insert(0, os.path.abspath("backend"))

from analytics.config import DetectionConfig
from app.api.routes.telemetry import get_telemetry_service
from app.core.config import get_settings
from app.db.models import EnergyWastageEvent, Machine, Site, Telemetry
from app.db.session import create_database_engine, create_session_factory
from app.main import create_app
from app.repositories.telemetry_repository import TelemetryRepository
from app.repositories.wastage_event_repository import WastageEventRepository
from app.services.analytics_orchestrator import AnalyticsOrchestrator
from app.services.telemetry_service import TelemetryService
from app.services.wastage_event_service import WastageEventService
from simulator.generator import TelemetryGenerator
from simulator.models import Scenario
from simulator.profiles import DEFAULT_PROFILE
from simulator.scenarios import ScenarioController


def run_scenario_validation(
    session: Session,
    app: Any,
    scenario: Scenario,
    duration_seconds: int,
    config: DetectionConfig | None = None,
) -> dict[str, Any]:
    # 1. Setup temporary Site and Machine in database
    site = Site(name=f"ValSite-{uuid4().hex[:6]}", timezone="UTC")
    session.add(site)
    session.flush()

    machine = Machine(
        site_id=site.id,
        machine_identifier=f"ValMachine-{uuid4().hex[:6]}",
        name=f"Validation Machine {scenario.name}",
        machine_type="conveyor",
        status="active",
    )
    session.add(machine)
    session.commit()

    # 2. Wire FastAPI telemetry service with DB session and orchestrator
    def override_telemetry_service() -> TelemetryService:
        t_repo = TelemetryRepository(session)
        w_repo = WastageEventRepository(session)
        w_service = WastageEventService(w_repo)
        orchestrator = AnalyticsOrchestrator(
            session=session,
            persistence_service=w_service,
            config=config,
        )
        return TelemetryService(t_repo, orchestrator=orchestrator)

    app.dependency_overrides[get_telemetry_service] = override_telemetry_service
    client = TestClient(app)

    controller = ScenarioController(scenario, DEFAULT_PROFILE)
    generator = TelemetryGenerator(machine_id=machine.id, interval_seconds=1.0)
    start_time = datetime(2026, 9, 26, 12, 0, 0, tzinfo=timezone.utc)

    samples_submitted = 0
    client.__enter__()
    try:
        # 3. Stream scenario samples through POST /api/v1/telemetry
        for s in range(duration_seconds):
            step = controller.step_at(float(s))
            record = generator.generate(
                step.state,
                timestamp=start_time + timedelta(seconds=s),
                state_elapsed_seconds=step.state_elapsed_seconds,
                power_multiplier=step.power_multiplier,
                load_fraction=step.load_fraction,
            )
            payload = record.to_payload()
            resp = client.post("/api/v1/telemetry", json=payload)
            if resp.status_code != 201:
                raise RuntimeError(f"POST /api/v1/telemetry returned {resp.status_code}: {resp.text}")
            samples_submitted += 1

        # 4. Finalize event episode: send a concluding STOPPED sample (representing machine shutdown)
        if scenario is not Scenario.START_STOP_CYCLING:
            final_record = generator.generate(
                controller.step_at(float(duration_seconds)).state,
                timestamp=start_time + timedelta(seconds=duration_seconds),
            )
            final_payload = final_record.to_payload()
            final_payload["operating_state"] = "stopped"
            final_payload["active_power"] = 0.0
            resp = client.post("/api/v1/telemetry", json=final_payload)
            if resp.status_code == 201:
                samples_submitted += 1

        # 5. Query results from database
        telemetry_persisted = session.scalar(
            select(func.count()).select_from(Telemetry).where(Telemetry.machine_id == machine.id)
        )
        events = session.scalars(
            select(EnergyWastageEvent).where(EnergyWastageEvent.machine_id == machine.id)
        ).all()

        reasons = [ev.detection_reason for ev in events]
        event_count = len(events)
        wasted_energies = [
            float(ev.estimated_wasted_energy_kwh) if ev.estimated_wasted_energy_kwh is not None else None
            for ev in events
        ]

        # 6. Test idempotency: re-trigger orchestrator to ensure no duplicates are generated
        t_repo = TelemetryRepository(session)
        w_repo = WastageEventRepository(session)
        w_service = WastageEventService(w_repo)
        orchestrator = AnalyticsOrchestrator(
            session=session,
            persistence_service=w_service,
            config=config,
        )
        orchestrator.process_machine(machine.id)
        events_after = session.scalars(
            select(EnergyWastageEvent).where(EnergyWastageEvent.machine_id == machine.id)
        ).all()
        duplicate_occurred = len(events_after) > event_count

    finally:
        client.__exit__(None, None, None)
        app.dependency_overrides.clear()

        # 7. Complete cleanup of all temporary data
        session.rollback()
        with session.get_bind().begin() as conn:
            conn.exec_driver_sql(
                "DELETE FROM energy_wastage_events WHERE machine_id = %(mid)s",
                {"mid": machine.id},
            )
            conn.exec_driver_sql(
                "DELETE FROM telemetry WHERE machine_id = %(mid)s",
                {"mid": machine.id},
            )
            conn.exec_driver_sql(
                "DELETE FROM machines WHERE id = %(mid)s",
                {"mid": machine.id},
            )
            conn.exec_driver_sql(
                "DELETE FROM sites WHERE id = %(sid)s",
                {"sid": site.id},
            )

        # 8. Confirm cleanup
        remaining_events = session.scalar(
            select(func.count()).select_from(EnergyWastageEvent).where(EnergyWastageEvent.machine_id == machine.id)
        )
        remaining_telemetry = session.scalar(
            select(func.count()).select_from(Telemetry).where(Telemetry.machine_id == machine.id)
        )
        cleanup_succeeded = (remaining_events == 0 and remaining_telemetry == 0)

    return {
        "scenario": scenario.value,
        "samples_submitted": samples_submitted,
        "telemetry_persisted": telemetry_persisted,
        "analytics_triggered": True,
        "event_reasons": reasons,
        "event_count": event_count,
        "wasted_energies": wasted_energies,
        "duplicate_occurred": duplicate_occurred,
        "cleanup_succeeded": cleanup_succeeded,
    }


def main() -> int:
    settings = get_settings()
    engine = create_database_engine(settings.database_url)
    session_factory = create_session_factory(engine)
    session = session_factory()
    app = create_app()

    # Scenario durations to satisfy production persistence thresholds:
    # - normal: 70s (checks no false positives across normal starting, running, low load)
    # - idle_wastage: 70s (> 60s idle threshold)
    # - low_load_wastage: 130s (> 120s low-load threshold)
    # - abnormal_power: 70s (> 60s abnormal threshold)
    # - start_stop_cycling: 70s (> 3 cycles of 19.5s each = 58.5s)
    scenarios = [
        (Scenario.NORMAL_OPERATION, 70),
        (Scenario.IDLE_WASTAGE, 70),
        (Scenario.LOW_LOAD_WASTAGE, 130),
        (Scenario.ABNORMAL_POWER, 70),
        (Scenario.START_STOP_CYCLING, 90),
    ]

    print("=" * 80)
    print("ORVEX STAGE 3D: AUTOMATED ANALYTICS PIPELINE END-TO-END VALIDATION")
    print("=" * 80)

    all_passed = True
    results = []
    total_start = time.monotonic()

    for sc, duration in scenarios:
        print(f"\nRunning scenario: {sc.value} (duration={duration}s)...")
        start_sc = time.monotonic()
        res = run_scenario_validation(session, app, sc, duration)
        elapsed_sc = time.monotonic() - start_sc
        results.append(res)

        print(f"  Samples submitted: {res['samples_submitted']}")
        print(f"  Telemetry persisted: {res['telemetry_persisted']}")
        print(f"  Analytics triggered: {res['analytics_triggered']}")
        print(f"  Detected event reasons: {res['event_reasons']}")
        print(f"  Number of persisted events: {res['event_count']}")
        print(f"  Estimated wasted energy (kWh): {res['wasted_energies']}")
        print(f"  Duplicate events occurred: {res['duplicate_occurred']}")
        print(f"  Cleanup succeeded: {res['cleanup_succeeded']}")
        print(f"  Execution time: {elapsed_sc:.2f}s")

        # Validation assertions
        if sc is Scenario.NORMAL_OPERATION:
            if res["event_count"] != 0:
                print(f"  [FAIL] Expected 0 events for normal operation, got {res['event_count']}!")
                all_passed = False
            else:
                print("  [PASS] 0 false events in normal operation.")
        elif sc is Scenario.START_STOP_CYCLING:
            if res["event_count"] != 1:
                print(f"  [FAIL] Expected 1 event for cycling, got {res['event_count']}")
                all_passed = False
            elif res["wasted_energies"][0] is not None:
                print(f"  [FAIL] Expected NULL wasted energy for cycling candidate, got {res['wasted_energies'][0]}!")
                all_passed = False
            else:
                print("  [PASS] 1 cycling event persisted with NULL wasted energy.")
        else:
            if res["event_count"] != 1:
                print(f"  [FAIL] Expected 1 event, got {res['event_count']}")
                all_passed = False
            elif res["wasted_energies"][0] is None or res["wasted_energies"][0] <= 0:
                print("  [FAIL] Expected positive wasted energy!")
                all_passed = False
            else:
                print(f"  [PASS] 1 event persisted with positive wasted energy: {res['wasted_energies'][0]:.4f} kWh")

        if res["duplicate_occurred"]:
            print("  [FAIL] Duplicate events detected upon re-processing!")
            all_passed = False

        if not res["cleanup_succeeded"]:
            print("  [FAIL] Temporary data was not completely cleaned up!")
            all_passed = False

    session.close()
    engine.dispose()
    total_elapsed = time.monotonic() - total_start

    print("\n" + "=" * 80)
    print(f"Validation completed in {total_elapsed:.2f}s")
    if all_passed:
        print("ALL 5 SCENARIOS PASSED VALIDATION SUCCESSFULLY.")
        print("=" * 80)
        return 0
    else:
        print("VALIDATION FAILED ON ONE OR MORE SCENARIOS.")
        print("=" * 80)
        return 1


if __name__ == "__main__":
    sys.exit(main())
